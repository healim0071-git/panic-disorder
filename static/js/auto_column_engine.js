  function checkAndRunAutoColumnPublish(isManual) {
    var state = getAutoColumnState();
    var now = Date.now();

    if (!isManual && now < state.nextScheduledTime) {
      updateStatusBadgeUI(state);
      return false; // Not yet scheduled time
    }

    // 🌟 핵심 요구사항: 하루 최대 1편 발행 락 (Daily Cap)
    // 수동 즉시 발행이 아닌 자동 스케줄의 경우, 오늘 날짜에 이미 발행된 칼럼이 있다면 당일 추가 발행을 원천 차단하고 다음 스케줄로 안전하게 연기
    if (!isManual) {
      var todayStr = formatDateOnly(new Date(now));
      var existingColsForToday = [];
      try {
        var rawC = localStorage.getItem(STORAGE_BOARD_KEY);
        if (rawC) existingColsForToday = JSON.parse(rawC) || [];
      } catch(e) {}
      var alreadyPublishedToday = existingColsForToday.some(function(item) {
        return item && (item.date === todayStr || (item.createdAt && formatDateOnly(new Date(item.createdAt)) === todayStr));
      });
      if (alreadyPublishedToday || (state.lastPublishedTime && formatDateOnly(new Date(state.lastPublishedTime)) === todayStr)) {
        if (state.nextScheduledTime <= now) {
          var nextD = calculateNextColumnSchedule(new Date());
          state.nextScheduledTime = nextD.getTime();
          saveAutoColumnState(state);
        }
        updateStatusBadgeUI(state);
        return false;
      }
    }

    var existingTitles = getExistingColumnTitles();
    var deletedPoolIds = getDeletedColumnPoolIds();

    // Determine article to publish from pool (Skip already published titles and deleted items)
    var poolIdx = (typeof state.poolIndex === 'number') ? state.poolIndex : 0;
    var selectedIdx = -1;

    for (var i = 0; i < columnsPool.length; i++) {
      var candidateIdx = (poolIdx + i) % columnsPool.length;
      var candidate = columnsPool[candidateIdx];
      var norm = normalizeColumnTitle(candidate.title);
      var pId = candidate.idPrefix || candidate.id;
      if (!existingTitles.has(norm) && !deletedPoolIds.has(String(pId))) {
        selectedIdx = candidateIdx;
        break;
      }
    }

    // Load current columns board to determine total existing count (with multi-source fallback)
    var currentColumns = [];
    try {
      var raw = localStorage.getItem(STORAGE_BOARD_KEY);
      if (raw) currentColumns = JSON.parse(raw) || [];
    } catch(e) {}
    if (currentColumns.length === 0) {
      if (typeof window !== 'undefined' && Array.isArray(window.defaultColumnsData)) {
        currentColumns = window.defaultColumnsData.slice();
      } else if (typeof window !== 'undefined' && Array.isArray(window.defaultColumnsList)) {
        currentColumns = window.defaultColumnsList.slice();
      }
    }

    var article = null;
    if (selectedIdx !== -1) {
      article = columnsPool[selectedIdx];
    } else {
      // 🌟 핵심 요구사항: 기본 풀 23편 소진 시 기존 글을 재탕(심층 연재)하지 않고,
      // 확장 임상 풀 및 동적 생성기(Continuous Clinical Generator)를 통해 새로운 고품질 글 생성!
      article = generateContinuousNewColumn(existingTitles, deletedPoolIds, state);
    }

    if (!article) {
      console.warn('[Healim Auto-Column Engine] 발행 가능한 미중복 칼럼을 찾을 수 없어 안전하게 중단합니다.');
      return false;
    }

    // Ensure published date is strictly newer than any existing seed post (seed max is 2026.09.10)
    var nowDate = new Date();
    var maxExistingTs = new Date('2026-09-19T23:59:59').getTime();
    if (Array.isArray(currentColumns)) {
      currentColumns.forEach(function(p) {
        if (p && p.date) {
          var dTs = new Date(String(p.date).replace(/[.\/]/g, '-')).getTime();
          if (!isNaN(dTs) && dTs > maxExistingTs) maxExistingTs = dTs;
        }
      });
    }
    var effectiveTs = Math.max(nowDate.getTime(), maxExistingTs);
    var effectiveDate = new Date(effectiveTs);
    var dateStr = formatDateOnly(effectiveDate);
    var postId = 'col-auto-' + now;

    var postTitle = sanitizeMedicalCompliance(article.title);
    var postContent = sanitizeMedicalCompliance(article.content);

    var newPost = {
      id: postId,
      poolId: article.idPrefix,
      category: '칼럼',
      author: '해아림한의원',
      date: dateStr,
      views: Math.floor(Math.random() * 150) + 180,
      image: article.image || '/images/columns/column_30_cure_homeostasis.svg',
      title: sanitizeMedicalCompliance(postTitle),
      summary: sanitizeMedicalCompliance(article.summary || ''),
      content: sanitizeMedicalCompliance(postContent),
      isAutoPublished: true,
      isCustom: true,
      createdAt: now,
      updatedAt: now
    };

    // 🌟 핵심 요구사항 1: 엄격한 중복 감지 시 강제 발행 즉시 중단!
    var normNew = normalizeColumnTitle(newPost.title);
    var dupFound = currentColumns.some(function(item) {
      return normalizeColumnTitle(item.title) === normNew;
    });
    if (dupFound || existingTitles.has(normNew)) {
      console.warn('[Healim Auto-Column Engine] 🚫 중복 칼럼 감지되어 발행을 즉각 중단합니다: "' + newPost.title + '"');
      state.poolIndex = (poolIdx + 1) % columnsPool.length;
      saveAutoColumnState(state);
      return false; // 강제 발행 취소!
    }

    // Insert at top of list
    currentColumns.unshift(newPost);
    try {
      localStorage.setItem(STORAGE_BOARD_KEY, JSON.stringify(currentColumns));

      // Save to Permanent Master Vault
      var vaultList = [];
      var rawV = localStorage.getItem('healim_vault_all_posts_columns');
      if (rawV) vaultList = JSON.parse(rawV) || [];
      vaultList = vaultList.filter(function(p) { return p.id !== newPost.id && normalizeColumnTitle(p.title) !== normalizeColumnTitle(newPost.title); });
      vaultList.unshift(newPost);
      localStorage.setItem('healim_vault_all_posts_columns', JSON.stringify(vaultList));

      // Save to IndexedDB
      if (typeof window !== 'undefined' && window.HealimPermanentDB && window.HealimPermanentDB.saveVault) {
        window.HealimPermanentDB.saveVault('columns', vaultList);
      }

      var customCols = [];
      var rawC = localStorage.getItem('healim_custom_columns_posts');
      if (rawC) customCols = JSON.parse(rawC) || [];
      customCols = customCols.filter(function(p) { return p.id !== newPost.id && normalizeColumnTitle(p.title) !== normalizeColumnTitle(newPost.title); });
      customCols.unshift(newPost);
      localStorage.setItem('healim_custom_columns_posts', JSON.stringify(customCols));

      var rawLeg = localStorage.getItem('healim_community_posts_v2');
      var legList = rawLeg ? (JSON.parse(rawLeg) || []) : [];
      legList = legList.filter(function(p) { return p.id !== newPost.id && normalizeColumnTitle(p.title) !== normalizeColumnTitle(newPost.title); });
      legList.unshift(newPost);
      localStorage.setItem('healim_community_posts_v2', JSON.stringify(legList));

      // Synchronize to Global Cloud DB & Universal Sync Engine
      if (typeof window !== 'undefined') {
        if (window.HealimCloudDB && typeof window.HealimCloudDB.savePost === 'function') {
          window.HealimCloudDB.savePost('columns', newPost);
        }
        if (window.HealimUniversalSync && typeof window.HealimUniversalSync.syncPostToRemote === 'function') {
          window.HealimUniversalSync.syncPostToRemote('columns', newPost, 'create');
        }
      }
    } catch(e) {}

    // Update state
    var nextSchedule = calculateNextColumnSchedule(new Date());
    state.lastPublishedTime = now;
    state.nextScheduledTime = nextSchedule.getTime();
    state.poolIndex = ((selectedIdx !== -1 ? selectedIdx : poolIdx) + 1) % columnsPool.length;
    saveAutoColumnState(state);

    updateStatusBadgeUI(state);

    // Notify community and all bottom sections
    try {
      window.dispatchEvent(new CustomEvent('healim-community-updated', {
        detail: {
          type: 'columns',
          post: newPost,
          isAutoPublished: true,
          nextScheduleTime: state.nextScheduledTime
        }
      }));
    } catch(e) {}

    console.log('[Healim Auto-Column Engine] Published column: "' + newPost.title + '" | Next schedule: ' + formatDateTime(state.nextScheduledTime));

    if (isManual && typeof window.alert === 'function') {
      alert('⚡ [공황장애 치료칼럼 신규 글 자동 발행 완료]\n\n' +
            '제목: ' + newPost.title + '\n' +
            '작성자: ' + newPost.author + ' (' + dateStr + ')\n' +
            '분량: 1,600자 내외 임상 칼럼\n' +
            '상태: 기존 작성글과 중복되지 않는 새로운 칼럼으로 목록 최상단에 발행되었습니다.\n\n' +
            '다음 자동 발행 예정: ' + formatDateTime(state.nextScheduledTime) + ' (오전 8시~11시 사이)');
    }

    return newPost;
  }

  function updateStatusBadgeUI(state) {
    var el = document.getElementById('autoColumnNextScheduleText');
    if (el) {
      el.textContent = formatDateTime(state.nextScheduledTime);
    }
  }

