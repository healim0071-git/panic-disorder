  function sanitizeStoredPosts() {
    try {
      var raw = localStorage.getItem(STORAGE_BOARD_KEY);
      if (!raw) return;
      var list = JSON.parse(raw);
      if (!Array.isArray(list)) return;
      var modified = false;
      list.forEach(function(post) {
        if (post && post.image && post.content) {
          var escaped = post.image.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
          var regex = new RegExp('^\\s*!\\[[^\\]]*\\]\\(' + escaped + '\\)\\s*', 'i');
          if (regex.test(post.content)) {
            post.content = post.content.replace(regex, '');
            modified = true;
          }
        }
      });
      if (modified) {
        localStorage.setItem(STORAGE_BOARD_KEY, JSON.stringify(list));
      }
    } catch(e) {}
  }
  sanitizeStoredPosts();

  /**
   * Calculate next schedule:
   * - 2~3 posts per week: 2 days later (50%) or 3 days later (50%) -> avg 2.5 days
   * - Strict random time between 08:00:00 and 10:59:59 AM
   */
  function calculateNextColumnSchedule(baseTime) {
    var base = (baseTime instanceof Date) ? baseTime : new Date();
    var dayOffset = Math.random() < 0.5 ? 2 : 3;
    var next = new Date(base.getTime() + dayOffset * 24 * 60 * 60 * 1000);

    // Random hour between 8 and 10 (8, 9, 10 -> strictly 08:00:00 to 10:59:59)
    var hour = 8 + Math.floor(Math.random() * 3);
    var minute = Math.floor(Math.random() * 60);
    var second = Math.floor(Math.random() * 60);

    next.setHours(hour, minute, second, 0);

    if (next.getTime() <= base.getTime()) {
      next = new Date(next.getTime() + 24 * 60 * 60 * 1000);
      next.setHours(hour, minute, second, 0);
    }
    return next;
  }

