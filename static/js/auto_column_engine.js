  function sanitizeStoredPosts() {
    try {
      var raw = localStorage.getItem(STORAGE_BOARD_KEY);
      if (!raw) return;
      var list = JSON.parse(raw);
      if (!Array.isArray(list)) return;
      var modified = false;
      list.forEach(function(post) {
        if (post && post.image && post.content) {
          var escaped = post.image.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
          var regex = new RegExp('^\\s*!\\[[^\\]]*\\]\\(' + escaped + '\\)\\s*', 'i');
          if (regex.test(post.content)) {
            post.content = post.content.replace(regex, '');
            modified = true;
          }
        }
      });
      if (modified) {
        localStorage.setItem(STORAGE_BOARD_KEY, JSON.stringify(list));
      }
    } catch(e) {}
  }
